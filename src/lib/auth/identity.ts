import { createClient, type SupabaseClient } from "@supabase/supabase-js";
import { env, supabaseBridgeConfigured } from "@/config/env";
import { hashPassword, verifyPassword as verifyLocalPassword } from "./crypto";

/**
 * Identity strategies.
 *
 * BEFORE THIS MODULE EXISTED, `AUTH_PROVIDER=supabase` was accepted by the
 * environment schema, reported in the UI and documented in the README — but the
 * login route never branched on it. Setting it silently kept local password
 * auth. That is exactly the kind of dead control this codebase forbids, so the
 * choice is now real:
 *
 *   local    → scrypt password hashes in `ctl_admin` (default, fully functional)
 *   supabase → password verified against Supabase Auth; `ctl_admin` holds the
 *              ROLE only, because authorization is an administrative decision
 *              that must not live in an IdP claim.
 *
 * When `supabase` is selected but its credentials are absent, verification fails
 * closed with `provider_unavailable` (HTTP 503). It never falls back to local
 * hashes — a silent fallback would authenticate against a store the operator
 * believes is unused.
 */

export type IdentityProviderName = "local" | "supabase";

export type VerifyResult =
  | { ok: true; externalUserId: string | null; mfaEnrolledExternally: boolean }
  | { ok: false; code: "invalid_credentials" | "provider_unavailable" | "upstream_error"; reason: string };

export type InviteResult =
  | { ok: true; externalUserId: string | null; deliveryNote: string }
  | { ok: false; code: "provider_unavailable" | "upstream_error" | "already_exists"; reason: string };

export interface IdentityProvider {
  readonly name: IdentityProviderName;
  /** Where the password lives. Drives what the login page may honestly claim. */
  readonly passwordStore: "control-plane-database" | "supabase-auth";
  /** Where the second factor is verified. */
  readonly mfaVerifier: "control-plane-totp" | "supabase-auth-totp";
  /** Whether invitation goes through an external mailer. */
  readonly invitationTransport: "signed-link-from-this-app" | "supabase-email";
  isConfigured(): { configured: boolean; detail: string };
  verify(email: string, password: string): Promise<VerifyResult>;
  invite(email: string, options: { redirectTo: string }): Promise<InviteResult>;
  /** Only meaningful for providers that hash locally. */
  hash?(password: string): Promise<string>;
}

// ---------------------------------------------------------------------------
// Local strategy
// ---------------------------------------------------------------------------

export const localIdentity: IdentityProvider = {
  name: "local",
  passwordStore: "control-plane-database",
  mfaVerifier: "control-plane-totp",
  invitationTransport: "signed-link-from-this-app",

  isConfigured() {
    return {
      configured: true,
      detail: "scrypt hashes in ctl_admin; TOTP verified by this application.",
    };
  },

  async verify(_email, _password) {
    // The local strategy is driven by the stored hash on the ctl_admin row, which
    // the caller already has. This exists so both strategies satisfy one shape.
    return { ok: true, externalUserId: null, mfaEnrolledExternally: false };
  },

  async invite() {
    return {
      ok: true,
      externalUserId: null,
      deliveryNote: "Single-use link generated by this application; no email is sent.",
    };
  },

  hash: hashPassword,
};

/** Verifies a password against a stored scrypt hash (local strategy). */
export async function verifyLocal(password: string, storedHash: string | null): Promise<boolean> {
  if (!storedHash) return false;
  return verifyLocalPassword(password, storedHash);
}

// ---------------------------------------------------------------------------
// Supabase strategy
// ---------------------------------------------------------------------------

let supabaseAuthClient: SupabaseClient | null = null;

function supabaseAuth(): SupabaseClient | null {
  const url = env.NEXT_PUBLIC_SUPABASE_URL;
  const anonKey = env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
  if (!url || !anonKey) return null;
  if (!supabaseAuthClient) {
    supabaseAuthClient = createClient(url, anonKey, {
      auth: {
        // The returned Supabase session is discarded: this application issues its
        // own digest-stored cookie. Persisting a second session would create two
        // sources of truth for "is this admin signed in".
        persistSession: false,
        autoRefreshToken: false,
        detectSessionInUrl: false,
      },
    });
  }
  return supabaseAuthClient;
}

function supabaseServiceClient(): SupabaseClient | null {
  const url = env.NEXT_PUBLIC_SUPABASE_URL;
  const serviceKey = env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !serviceKey) return null;
  return createClient(url, serviceKey, {
    auth: { persistSession: false, autoRefreshToken: false },
  });
}

export const supabaseIdentity: IdentityProvider = {
  name: "supabase",
  passwordStore: "supabase-auth",
  mfaVerifier: "supabase-auth-totp",
  invitationTransport: "supabase-email",

  isConfigured() {
    const hasAuth = Boolean(env.NEXT_PUBLIC_SUPABASE_URL && env.NEXT_PUBLIC_SUPABASE_ANON_KEY);
    const hasService = Boolean(env.SUPABASE_SERVICE_ROLE_KEY);
    if (!hasAuth) {
      return {
        configured: false,
        detail:
          "NEXT_PUBLIC_SUPABASE_URL and NEXT_PUBLIC_SUPABASE_ANON_KEY are required to verify a password against Supabase Auth.",
      };
    }
    if (!hasService) {
      return {
        configured: true,
        detail:
          "Password verification available. Invitations need SUPABASE_SERVICE_ROLE_KEY (auth.admin.inviteUserByEmail) and are refused without it.",
      };
    }
    return { configured: true, detail: "Password verification and admin invitations available." };
  },

  async verify(email, password) {
    const client = supabaseAuth();
    if (!client) {
      return {
        ok: false,
        code: "provider_unavailable",
        reason:
          "AUTH_PROVIDER=supabase but the Supabase URL/anon key are not configured. Refusing to fall back to local password hashes.",
      };
    }

    const { data, error } = await client.auth.signInWithPassword({ email, password });
    if (error) {
      // Supabase returns "Invalid login credentials" for both unknown user and
      // wrong password — already free of an account-existence oracle.
      const message = error.message ?? "unknown";
      const upstream = /rate limit|timeout|fetch failed|network/i.test(message);
      return {
        ok: false,
        code: upstream ? "upstream_error" : "invalid_credentials",
        // Never echo the upstream body verbatim: it can carry request material.
        reason: upstream ? "Supabase Auth could not be reached." : "Email or password is incorrect.",
      };
    }

    const user = data?.user ?? null;
    if (!user) {
      return { ok: false, code: "invalid_credentials", reason: "Email or password is incorrect." };
    }

    const factors = data?.user?.factors ?? [];
    const mfaEnrolledExternally = factors.some(
      (factor) => factor.factor_type === "totp" && factor.status === "verified",
    );

    return { ok: true, externalUserId: user.id, mfaEnrolledExternally };
  },

  async invite(email, options) {
    const client = supabaseServiceClient();
    if (!client) {
      return {
        ok: false,
        code: "provider_unavailable",
        reason:
          "Inviting through Supabase Auth needs SUPABASE_SERVICE_ROLE_KEY. Refusing to create a control-plane-only invite that the operator would believe is a Supabase identity.",
      };
    }

    const { data, error } = await client.auth.admin.inviteUserByEmail(email, {
      redirectTo: options.redirectTo,
    });
    if (error) {
      const already = /already been registered|already exists/i.test(error.message ?? "");
      return {
        ok: false,
        code: already ? "already_exists" : "upstream_error",
        reason: already
          ? `${email} already exists in Supabase Auth. Link the existing identity instead of re-inviting.`
          : `Supabase Auth rejected the invitation: ${error.code ?? "upstream_error"}.`,
      };
    }

    return {
      ok: true,
      externalUserId: data?.user?.id ?? null,
      deliveryNote: "Invitation email sent by Supabase Auth. The password is set there, not here.",
    };
  },
};

// ---------------------------------------------------------------------------
// Resolution
// ---------------------------------------------------------------------------

export function identityProvider(): IdentityProvider {
  return env.AUTH_PROVIDER === "supabase" ? supabaseIdentity : localIdentity;
}

/** Truthful description of the active identity configuration, for the UI. */
export function identityStatus() {
  const provider = identityProvider();
  const { configured, detail } = provider.isConfigured();
  return {
    provider: provider.name,
    configured,
    detail,
    passwordStore: provider.passwordStore,
    mfaVerifier: provider.mfaVerifier,
    invitationTransport: provider.invitationTransport,
    bridgeConfigured: supabaseBridgeConfigured,
  };
}
